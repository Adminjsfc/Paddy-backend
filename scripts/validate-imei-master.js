// Validate IMEI/GPS behavior against the configured database, then roll back all fixtures.
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { pool } from '../src/config/database.js';
import { one } from '../src/repositories/database.js';
import { createMaster, setMasterStatus, updateMasterProfile } from '../src/services/masters.service.js';
import { ingestPacket } from '../src/services/gps.service.js';
import { profilePatches } from '../src/config/masters.js';
import * as S from '../src/validators/schemas.js';

const c = await pool.getConnection();
try {
  await c.beginTransaction();
  const miller = await one(c, "SELECT f.* FROM facilities f JOIN tbl_district_master d ON d.id=f.district_id AND d.status=1 JOIN tbl_block_master b ON b.id=f.block_id AND b.district_id=f.district_id WHERE f.kind='MILLER' AND f.active=1 LIMIT 1");
  const type = await one(c, 'SELECT id FROM vehicle_types WHERE active=1 LIMIT 1');
  const user = { role: 'ADMIN' };
  const suffix = crypto.randomBytes(5).toString('hex').toUpperCase();
  const identity = S.imeiMaster.parse({ imei: String(BigInt('0x' + suffix)).padStart(15, '0'), provider: 'ROLLBACK IMEI VALIDATION', district_id: miller.district_id, block_id: miller.block_id });
  const imei = await createMaster(c, 'imeis', identity, user);
  assert.equal(imei.mapping_status, null);
  assert.equal(imei.status_updated_at, null);
  const imeiContext = { user, params: { id: imei.id } };
  await updateMasterProfile(c, { provider: 'Before mapping' }, imeiContext, profilePatches.imeis, 'imeis');
  const initial = await one(c, 'SELECT mapping_status,status_updated_at FROM imeis WHERE id=?', [imei.id]);
  assert.equal(initial.mapping_status, null);
  assert.equal(initial.status_updated_at, null);
  await assert.rejects(createMaster(c, 'imeis', identity, user), { code: 'ER_DUP_ENTRY' });
  const vehicle = await createMaster(c, 'vehicles', S.vehicle.parse({ miller_id: miller.id, vehicle_type_id: type.id, registration_no: 'VAL' + suffix, capacity: { value: 10, unit: 'MT' } }), user);
  const assignment = S.device.parse({ imei_id: imei.id, vehicle_id: vehicle.id, district_id: miller.district_id, block_id: miller.block_id });
  assert.equal(vehicle.mapping_status, null);
  assert.equal(vehicle.status_updated_at, null);
  const device = await createMaster(c, 'gps-devices', assignment, user);
  const mapped = await one(c, 'SELECT * FROM imeis WHERE id=?', [imei.id]);
  assert.equal(mapped.mapping_status, 'MAPPED');
  assert(mapped.status_updated_at);
  const mappedVehicle = await one(c, 'SELECT mapping_status,status_updated_at FROM vehicles WHERE id=?', [vehicle.id]);
  assert.equal(mappedVehicle.mapping_status, 'MAPPED');
  assert(mappedVehicle.status_updated_at);
  assert.equal(mapped.district_id, miller.district_id);
  assert.equal(mapped.block_id, miller.block_id);
  await assert.rejects(createMaster(c, 'gps-devices', assignment, user), { code: 'ER_DUP_ENTRY' });
  const deviceContext = { user, params: { id: device.id } };
  await assert.rejects(setMasterStatus(c, { active: false }, imeiContext, 'imeis'), { code: 'IMEI_IN_USE' });
  const packet = S.gps.parse({ imei: identity.imei, gps_at: new Date(Date.now() - 1000).toISOString(), latitude: 23.3, longitude: 85.3, speed_kph: 12, gps_fix: true, packet_type: 'PVT', raw: { validation: true } });
  assert.equal((await ingestPacket(c, packet)).result, 'NO_ACTIVE_SHIPMENT');
  assert.equal((await ingestPacket(c, packet)).result, 'DUPLICATE');
  const saved = await one(c, 'SELECT d.*,i.imei,i.provider FROM gps_devices d JOIN imeis i ON i.id=d.imei_id WHERE d.id=?', [device.id]);
  assert.equal(saved.imei, identity.imei);
  assert.equal(saved.district_id, miller.district_id);
  assert.equal(Number(saved.latitude), 23.3);
  assert.equal(Number(saved.longitude), 85.3);
  assert.equal(Number(saved.speed_kph), 12);
  assert(saved.last_gps_at);
  await updateMasterProfile(c, { provider: 'Updated provider' }, imeiContext, profilePatches.imeis, 'imeis');
  const unchanged = await one(c, 'SELECT mapping_status,status_updated_at FROM imeis WHERE id=?', [imei.id]);
  assert.equal(unchanged.mapping_status, 'MAPPED');
  assert.equal(unchanged.status_updated_at.getTime(), mapped.status_updated_at.getTime());
  await updateMasterProfile(c, { capacity: { value: 11, unit: 'MT' } }, { user, params: { id: vehicle.id } }, profilePatches.vehicles, 'vehicles');
  const editedVehicle = await one(c, 'SELECT mapping_status,status_updated_at FROM vehicles WHERE id=?', [vehicle.id]);
  assert.equal(editedVehicle.mapping_status, 'MAPPED');
  assert.equal(editedVehicle.status_updated_at.getTime(), mappedVehicle.status_updated_at.getTime());
  await updateMasterProfile(c, { district_id: miller.district_id, block_id: miller.block_id }, deviceContext, profilePatches['gps-devices'], 'gps-devices');
  await setMasterStatus(c, { active: false }, deviceContext, 'gps-devices');
  const unmapped = await one(c, 'SELECT * FROM imeis WHERE id=?', [imei.id]);
  assert.equal(unmapped.mapping_status, 'AVAILABLE');
  assert(unmapped.status_updated_at);
  assert.equal((await one(c, 'SELECT mapping_status FROM vehicles WHERE id=?', [vehicle.id])).mapping_status, 'AVAILABLE');
  await setMasterStatus(c, { active: true }, deviceContext, 'gps-devices');
  assert.equal((await one(c, 'SELECT mapping_status FROM imeis WHERE id=?', [imei.id])).mapping_status, 'MAPPED');
  assert.equal((await one(c, 'SELECT mapping_status FROM vehicles WHERE id=?', [vehicle.id])).mapping_status, 'MAPPED');
  await setMasterStatus(c, { active: false }, deviceContext, 'gps-devices');
  await setMasterStatus(c, { active: false }, imeiContext, 'imeis');
  await assert.rejects(createMaster(c, 'gps-devices', assignment, user), { status: 404 });
  await assert.rejects(setMasterStatus(c, { active: true }, deviceContext, 'gps-devices'), { status: 404 });
  console.log('IMEI master, assignment uniqueness, provider/location updates, packet ingestion and deletion guards passed. Fixtures rolled back.');
} finally {
  await c.rollback();
  c.release();
  await pool.end();
}
