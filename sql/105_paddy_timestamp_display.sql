UPDATE gps_devices d JOIN shipments s ON s.vehicle_id=d.vehicle_id
SET d.last_gps_at=DATE_SUB(d.last_gps_at,INTERVAL 330 MINUTE)
WHERE s.last_gps_at IS NOT NULL AND TIMESTAMPDIFF(SECOND,s.last_gps_at,d.last_gps_at)=19800;
