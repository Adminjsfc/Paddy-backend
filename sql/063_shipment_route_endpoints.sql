INSERT INTO shipment_routes(source_id,destination_id,source_lat,source_lng,destination_lat,destination_lng,geometry)
SELECT s.source_id,s.destination_id,s.source_lat,s.source_lng,s.destination_lat,s.destination_lng,NULL
FROM shipments s
WHERE s.id=(SELECT MIN(old.id) FROM shipments old WHERE old.source_id=s.source_id AND old.destination_id=s.destination_id)
AND NOT EXISTS(SELECT 1 FROM shipment_routes r WHERE r.source_id=s.source_id AND r.destination_id=s.destination_id);
UPDATE shipments s JOIN shipment_routes r ON r.source_id=s.source_id AND r.destination_id=s.destination_id SET s.route_id=r.id;
