import {mutation} from '../middlewares/mutation.js';
import {driver} from '../validators/schemas.js';
import {requestContext, respond} from '../utils/http.js';
import * as service from '../services/drivers.service.js';
import * as reports from '../services/driver-reports.service.js';
export const create = mutation(driver, (connection,data,req) => service.ensureDriver(connection,data,requestContext(req)));
export const list = async (req,res) => respond(res,await service.listDrivers(requestContext(req)));
export const tripSummary = async (req,res) => respond(res,await service.tripSummary(requestContext(req)));
export const details = async (req,res) => respond(res,await reports.details(requestContext(req)));
export const active = async (req,res) => respond(res,await reports.active(requestContext(req)));
export const tripDetails = async (req,res) => respond(res,await reports.tripDetails(requestContext(req)));
export const alerts = async (req,res) => respond(res,await reports.alertReport(requestContext(req)));
